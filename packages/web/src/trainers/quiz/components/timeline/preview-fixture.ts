const NOW = { year: 2026, month: 9, day: 24 };

function precisionOf(start: string): TimelineEvent["precision"] {
  const parts = start.replace(/^-/, "").split("-").length;
  return parts === 3 ? "day" : parts === 2 ? "month" : "year";
}

export const PREVIEW_TIMELINE: readonly TimelineItem[] = ROWS.flatMap(
  ([id, domain, kind, start, end, labelEn, labelDe, question, answer, extra = {}]) => {
    const { learning, wiki, ...rest } = extra;
    const event: TimelineEvent = {
      kind,
      start,
      end,
      precision: precisionOf(start),
      approx: false,
      ongoing: false,
      labelEn,
      labelDe,
      ...rest,
    };
    const slug = labelEn.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "");
    const item = toTimelineItem(
      id,
      domain,
      event,
      { known: !learning, lastReviewedAt: "2026-09-20T18:30:00.000Z" },
      NOW,
      {
        en: question,
        de: question,
        answerEn: answer,
        answerDe: answer,
        source: {
          url: wiki ?? `https://en.wikipedia.org/wiki/${slug}`,
          title: `${labelEn} – Wikipedia`,
          lang: wiki ? "de" : "en",
        },
      },
    );
    return item ? [item] : [];
  },
).sort((a, b) => a.parsed.startKey - b.parsed.startKey);
