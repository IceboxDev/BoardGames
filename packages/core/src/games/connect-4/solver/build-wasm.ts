/**
 * The C solver's engine as WebAssembly, embedded in TS:
 *
 *   pnpm --filter @boardgames/core c4-wasm
 *     = wasi-sdk clang native/c4wasm.c (+ native/c4core.h) → wasm32, freestanding
 *       + write wasm/c4-wasm.gen.ts (the module as base64 — no runtime file, so
 *         it loads the same in the browser's worker, the bundled server and Node)
 *
 * The toolchain is the one The Hunger uses: WASI_SDK=… overrides
 * ~/.local/wasi-sdk-34.0-x86_64-linux. Regenerate after any change under native/.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join } from "node:path";

const here = import.meta.dirname;
const sdk = process.env.WASI_SDK ?? join(homedir(), ".local/wasi-sdk-34.0-x86_64-linux");
const dir = mkdtempSync(join(tmpdir(), "c4-wasm-"));
const wasm = join(dir, "c4.wasm");
execFileSync(
  join(sdk, "bin/clang"),
  [
    "--target=wasm32",
    "-O3",
    "-nostdlib",
    "-Wall",
    "-Wextra",
    "-Werror",
    "-Wl,--no-entry",
    "-Wl,--strip-all",
    "-o",
    wasm,
    join(here, "native/c4wasm.c"),
  ],
  { stdio: "inherit" },
);
const bytes = readFileSync(wasm);
rmSync(dir, { recursive: true });
const sha = createHash("sha256").update(bytes).digest("hex");
const out = join(here, "wasm/c4-wasm.gen.ts");
writeFileSync(
  out,
  `// GENERATED by \`pnpm --filter @boardgames/core c4-wasm\` — DO NOT EDIT.
// The C solver's engine (native/c4wasm.c + native/c4core.h) as freestanding
// WebAssembly, embedded as base64; see ../wasm-engine.ts.
// ${bytes.length} bytes, sha256 ${sha}

export const C4_WASM_BASE64 = "${bytes.toString("base64")}";
`,
);
console.log(`${out}: ${bytes.length} bytes`);
