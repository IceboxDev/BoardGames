/**
 * Codegen: emit the C++ data tables for The Hunger from the TS content — the
 * single source of truth. Run: `pnpm gen-cpp-hunger` (or
 * `cd packages/core && npx tsx ../../scripts/gen-cpp-hunger.ts`).
 *
 * Outputs cpp/the-hunger/include/hg/data.gen.hpp (counts) and
 * cpp/the-hunger/src/{cards,missions,bonus_tokens,board}.gen.cpp.
 *
 * Load-bearing orders (parity):
 *   - Physical card, Mission and Bonus-token ints are assigned in JavaScript's
 *     default string sort order (UTF-16 code units), so "sort the string pool"
 *     (determinize.ts, rules.missionKeepSets) is "sort the ints" in C++.
 *   - The expand(...) lists are emitted in TS order (they feed the shuffles).
 *   - Spaces keep the board file's order; adjacency lists are emitted exactly
 *     as board.buildGraph sorts them, and each space gets a code-unit rank and
 *     a `localeCompare` rank (walk / Spicy destinations sort by the latter).
 * The output is deterministic: CI can regenerate and diff.
 */
