function bonusRow(id: string): string {
  const h = id.indexOf("#");
  const def = BONUS_TOKENS.find((b) => b.id === id.slice(0, h));
  if (!def) throw new Error(id);
  const b = def.bonus;
  const c = b.kind === "human" ? cat(b.category) : -1;
  const n = b.kind === "speed" ? b.n : 0;
  return `  {${q(id)}, ${idx(BONUS_KINDS, b.kind, "bonus")}, ${c}, ${n}},`;
}
