const BOARD_IDS = ["A", "B", "test"] as const;
let maxSpaces = 0;

function boardBlock(name: (typeof BOARD_IDS)[number]): string {
  const def: BoardDef = BOARDS[name];
  const g = buildGraph(def);
  const ids = def.spaces.map((s) => s.id);
  const si = (id: string) => {
    const i = ids.indexOf(id);
    if (i < 0) throw new Error(`${name}: unknown space ${id}`);
    return i;
  };
  maxSpaces = Math.max(maxSpaces, ids.length);
  const cu = [...ids].sort();
  const loc = [...ids].sort((a, b) => a.localeCompare(b));
  const adjStart: number[] = [];
  const adjList: number[] = [];
  for (const id of ids) {
    adjStart.push(adjList.length);
    for (const n of g.adj.get(id) ?? []) adjList.push(si(n));
  }
  adjStart.push(adjList.length);
  const dist = (m: ReadonlyMap<string, number>) =>
    ids.map((id) => {
      const d = m.get(id);
      if (d === undefined) throw new Error(`${name}: ${id} unreachable`);
      return d;
    });
  const chests = def.spaces.filter((s) => s.effect === "chest" || s.effect === "chest-open");
  const crypts = def.spaces.filter((s) => s.effect === "crypt");
  const p = `B_${name.toUpperCase()}`;
  return `
// ---- Board ${name} ----
static const Space ${p}_SPACES[] = {
${def.spaces
  .map(
    (s) =>
      `  {${q(s.id)}, ${region(s.region)}, ${s.path === null ? -1 : idx(PATHS, s.path, "path")}, ${idx(SPACE_EFFECTS, s.effect, "effect")}, ${s.mountainPenalty ?? -1}},`,
  )
  .join("\n")}
};
static const uint16_t ${p}_ADJ_START[] = {${adjStart.join(", ")}};
static const uint8_t ${p}_ADJ[] = {
${intList(adjList)}
};
static const uint8_t ${p}_CASTLE_DIST[] = {
${intList(dist(g.castleDist))}
};
static const uint8_t ${p}_LABYRINTH_DIST[] = {
${intList(dist(g.labyrinthDist))}
};
static const uint8_t ${p}_CU_RANK[] = {
${intList(ids.map((id) => cu.indexOf(id)))}
};
static const uint8_t ${p}_LOCALE_RANK[] = {
${intList(ids.map((id) => loc.indexOf(id)))}
};
static const uint8_t ${p}_CHESTS[] = {${chests.map((s) => si(s.id)).join(", ")}};
static const uint8_t ${p}_CRYPTS[] = {${crypts.map((s) => si(s.id)).join(", ")}};
`;
}

function boardInit(name: (typeof BOARD_IDS)[number]): string {
  const def = BOARDS[name];
  const g = buildGraph(def);
  const ids = def.spaces.map((s) => s.id);
  const p = `B_${name.toUpperCase()}`;
  const tavern = def.spaces.find((s) => s.effect === "tavern");
  const nChests = def.spaces.filter((s) => s.effect === "chest" || s.effect === "chest-open").length;
  const nCrypts = def.spaces.filter((s) => s.effect === "crypt").length;
  return `  {${q(name)}, ${ids.length}, ${p}_SPACES, ${p}_ADJ_START, ${p}_ADJ, ${ids.indexOf(g.castle)}, ${ids.indexOf(g.labyrinth)}, ${tavern ? ids.indexOf(tavern.id) : -1}, ${p}_CASTLE_DIST, ${p}_LABYRINTH_DIST, ${p}_CU_RANK, ${p}_LOCALE_RANK, ${nChests}, ${p}_CHESTS, ${nCrypts}, ${p}_CRYPTS},`;
}

const boardBlocks = BOARD_IDS.map(boardBlock).join("");
const boardCpp = `${BANNER}#include "hg/data.hpp"

namespace hg {
${boardBlocks}
const BoardData BOARD_DATA[3] = {
${BOARD_IDS.map(boardInit).join("\n")}
};

}  // namespace hg
`;

let maxChests = 0;
let maxCrypts = 0;
for (const b of BOARD_IDS) {
  maxChests = Math.max(
    maxChests,
    BOARDS[b].spaces.filter((s) => s.effect === "chest" || s.effect === "chest-open").length,
  );
  maxCrypts = Math.max(maxCrypts, BOARDS[b].spaces.filter((s) => s.effect === "crypt").length);
}
if (maxSpaces > 64) throw new Error("more than 64 spaces: widen the Well mask");

const header = `${BANNER}#pragma once

namespace hg {

constexpr int MAX_PLAYERS = ${VAMPIRES.length};
constexpr int NUM_DEFS = ${DEFS.length};
constexpr int NUM_CARDS = ${physicalSorted.length};
constexpr int NUM_HUNT = ${huntExpand.length};
constexpr int NUM_ROOKIE_A = ${rookieSplit.a.length};
constexpr int NUM_ROOKIE_REST = ${rookieSplit.rest.length};
constexpr int NUM_ROSES = ${roseExpand.length};
constexpr int NUM_STARTING = ${startingExpand[0].length};
constexpr int NUM_FAMILIES = ${families.length};
constexpr int FAM_ROSE = ${families.indexOf("rose")};
constexpr int NUM_MISSIONS = ${missionSorted.length};
constexpr int NUM_BONUS = ${bonusSorted.length};
constexpr int MAX_SPACES = ${maxSpaces};
constexpr int MAX_CHESTS = ${maxChests};
constexpr int MAX_CRYPTS = ${maxCrypts};

}  // namespace hg
`;

