const missionSorted = MISSIONS.map((m) => m.id).sort();
if (new Set(missionSorted).size !== missionSorted.length) throw new Error("duplicate mission");
const mi = (id: string) => missionSorted.indexOf(id);

function missionRow(id: string): string {
  const m = MISSIONS.find((x) => x.id === id);
  if (!m) throw new Error(id);
  const s = m.standard as Record<string, unknown> | undefined;
  const n = (k: string, dflt = 0) => (s && typeof s[k] === "number" ? (s[k] as number) : dflt);
  let of = -1;
  if (s && s.kind === "majority") {
    of = s.of === "humans" ? 4 : s.of === "familiars" ? 5 : cat(s.of as string);
  }
  const kwMask =
    s && Array.isArray(s.keywords)
      ? (s.keywords as string[]).reduce((acc, k) => acc | (1 << idx(KEYWORDS, k, "keyword")), 0)
      : 0;
  const distinct = s && s.kind === "per-distinct" ? idx(CARD_TYPES, s.type as string, "type") : -1;
  const rank = s && s.kind === "score-rank" ? (s.rank === "highest" ? 0 : 1) : -1;
  const inst = m.instant;
  const instRegion = inst && inst.kind === "free-hunt-same-column" ? region(inst.region) : -1;
  return (
    `  {${q(m.id)}, ${m.vp}, ${m.fivePlus === true}, ${m.whiteTitle === true}, ` +
    `${s ? idx(STD_KINDS, s.kind as string, "standard") : -1}, ${s && typeof s.category === "string" ? cat(s.category) : -1}, ` +
    `${of}, ${n("vpEach")}, ${n("perBeaten")}, ${n("min")}, ${n("max", -1)}, ${n("atLeast")}, ` +
    `${kwMask}, ${distinct}, ${rank}, ${inst ? idx(INSTANT_KINDS, inst.kind, "instant") : -1}, ${instRegion}},`
  );
}

