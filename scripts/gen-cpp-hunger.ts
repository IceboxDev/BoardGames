const idx = <T extends string>(list: readonly T[], v: string | undefined, what: string): number => {
  if (v === undefined) return -1;
  const i = (list as readonly string[]).indexOf(v);
  if (i < 0) throw new Error(`unknown ${what}: ${v}`);
  return i;
};
const cat = (c: string | undefined) => idx(HUMAN_CATEGORIES, c, "category");
const region = (r: string | undefined) => idx(REGIONS, r, "region");

/** Every string the C++ writes into canonical text must need no JSON escaping. */
function plain(s: string): string {
  if (!/^[A-Za-z0-9#_.,:~+-]+$/.test(s)) throw new Error(`id needs escaping: ${JSON.stringify(s)}`);
  return s;
}
const q = (s: string) => `"${plain(s)}"`;

// ---------------------------------------------------------------------------
// Cards
// ---------------------------------------------------------------------------

const DEFS: CardDef[] = [...HUNT_CARDS, ...ROSES, ...STARTING];
const defIndex = new Map(DEFS.map((d, i) => [d.id, i]));
if (defIndex.size !== DEFS.length) throw new Error("duplicate card def id");
if (CARD_DEFS.size !== DEFS.length) throw new Error("CARD_DEFS differs from the def list");

const huntExpand = expand(HUNT_CARDS);
const rookieSplit = expandByRookie(HUNT_CARDS);
const roseExpand = expand(ROSES);
const startingExpand = VAMPIRES.map((_, p) => expand(STARTING, `${p}-`));
const allPhysical = [...huntExpand, ...roseExpand, ...startingExpand.flat()];
const physicalSorted = [...allPhysical].sort();
if (new Set(physicalSorted).size !== physicalSorted.length) throw new Error("duplicate physical card");
const cardInt = new Map(physicalSorted.map((id, i) => [id, i]));
const ci = (id: string) => {
  const v = cardInt.get(id);
  if (v === undefined) throw new Error(`unknown physical card ${id}`);
  return v;
};
const defOfPhysical = (id: string) => {
  const h = id.indexOf("#");
  const d = defIndex.get(h === -1 ? id : id.slice(0, h));
  if (d === undefined) throw new Error(`no def for ${id}`);
  return d;
};

const families = [...new Set(DEFS.map((d) => d.family).filter((f): f is string => !!f))].sort();
const familyIdx = (f: string | undefined) => (f === undefined ? -1 : families.indexOf(f));

function defRow(d: CardDef): string {
  const kw = d.keywords.reduce((m, k) => m | (1 << idx(KEYWORDS, k, "keyword")), 0);
  const speedVar = typeof d.speed !== "number";
  const speedBase = typeof d.speed === "number" ? d.speed : d.speed.base;
  const speedHuman = typeof d.speed === "number" ? d.speed : d.speed.ifHuman;
  const m = d.manipulation;
  const manip = !m
    ? "{0, 0, -1, false, 1}"
    : m.kind === "draw"
      ? `{1, ${m.n}, ${m.withHuman ?? -1}, ${m.mandatory ? "true" : "false"}, 1}`
      : `{2, 0, -1, false, ${m.times ?? 1}}`;
  const passives = passivesOf(d);
  if (passives.length > 2) throw new Error(`${d.id}: more than 2 passives`);
  const pRow = (i: number) => {
    const p = passives[i];
    if (!p) return "{-1, 0, 0, 0, 0, 0, 0, 0}";
    const f = p as Record<string, unknown>;
    const n = (k: string) => (typeof f[k] === "number" ? (f[k] as number) : 0);
    const when = p.kind === "end-turn-vp" ? idx(WHEN, p.when, "when") : 0;
    return `{${idx(PASSIVE_KINDS, p.kind, "passive")}, ${n("n")}, ${when}, ${n("min")}, ${n("max")}, ${n("atLeast")}, ${n("speed")}, ${n("vp")}}`;
  };
  const a = d.activated;
  const act = !a
    ? "{-1, 0, 0}"
    : `{${idx(ACTIVATED, a.kind, "activated")}, ${"vp" in a ? a.vp : 0}, ${"draw" in a ? a.draw : 0}}`;
  const e = d.endGame;
  let eg = "{-1, -1, -1, -1, 0}";
  if (e) {
    const other =
      e.kind === "if-has"
        ? (defIndex.get(e.other) ??
          (() => {
            throw new Error(`${d.id}: unknown other ${e.other}`);
          })())
        : -1;
    const fam = e.kind === "if-family" || e.kind === "per-family" ? familyIdx(e.family) : -1;
    const c = e.kind === "per-category" ? cat(e.category) : -1;
    eg = `{${idx(END_GAME, e.kind, "endGame")}, ${other}, ${fam}, ${c}, ${e.vp}}`;
  }
  const hb = d.huntBonus ? `${region(d.huntBonus.region)}, ${d.huntBonus.vp}` : "-1, 0";
  return (
    `  {${q(d.id)}, ${idx(CARD_TYPES, d.type, "type")}, ${cat(d.category)}, ${familyIdx(d.family)}, ` +
    `${speedVar}, ${speedBase}, ${speedHuman}, ${d.vp}, ${kw}, ${manip}, ${passives.length}, ` +
    `{${pRow(0)}, ${pRow(1)}}, ${act}, ${hb}, ${d.onHunt?.kind === "digest-any"}, ${eg}, ` +
    `${d.rookie === true}, ${d.rookieCopies ?? -1}, ${d.copies}},`
  );
}

const intList = (xs: readonly number[]) => {
  const lines: string[] = [];
  for (let i = 0; i < xs.length; i += 16) lines.push(`  ${xs.slice(i, i + 16).join(", ")},`);
  return lines.join("\n");
};

